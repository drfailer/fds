!==============================================================================
! Thread-safe kernel wrappers (bypass orchestration, call kernels directly)
! RECURSIVE keyword ensures thread-safety (does not propagate to callees)
!==============================================================================

RECURSIVE SUBROUTINE C_FDS_VELOCITY_CORRECTOR_KERNEL(NM, T, DT) BIND(C, NAME="fds_velocity_corrector_kernel")
    USE VELO_KERNELS, ONLY: VELOCITY_CORRECTOR_KERNEL
    USE MESH_VARIABLES, ONLY: MESHES
    INTEGER(C_INT), VALUE :: NM
    REAL(C_DOUBLE), VALUE :: T, DT
    ! Call kernel directly without POINT_TO_MESH - thread-safe
    CALL VELOCITY_CORRECTOR_KERNEL(MESHES(NM), DT)
END SUBROUTINE C_FDS_VELOCITY_CORRECTOR_KERNEL

RECURSIVE SUBROUTINE C_FDS_VELOCITY_PREDICTOR_KERNEL(NM, T, DT) BIND(C, NAME="fds_velocity_predictor_kernel")
    USE VELO_KERNELS, ONLY: VELOCITY_PREDICTOR_KERNEL, &
                            CHECK_STABILITY_KERNEL
    USE MESH_VARIABLES, ONLY: MESHES
    INTEGER(C_INT), VALUE :: NM
    REAL(C_DOUBLE), VALUE :: T, DT
    IF (SOLID_PHASE_ONLY) RETURN
    ! Call kernels directly without POINT_TO_MESH - thread-safe
    CALL VELOCITY_PREDICTOR_KERNEL(MESHES(NM), DT)
    CALL CHECK_STABILITY_KERNEL( &
        MESHES(NM), DT, DT_NEW(NM), T, NM)
    ! Instability check (matches velo.f90:613-614)
    IF (DT_NEW(NM)<DT_INITIAL*LIMITING_DT_RATIO &
        .AND. (T+DT_NEW(NM)<(T_END-TWENTY_EPSILON_EB))) &
        STOP_STATUS = INSTABILITY_STOP
END SUBROUTINE C_FDS_VELOCITY_PREDICTOR_KERNEL

!> Velocity predictor kernel only (no CFL check).
