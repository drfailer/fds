        EST_FLAG, GX, GY, GZ)
    IF (CC_IBM) THEN
        CALL CUTFACE_VELOCITIES(MESHES(NM), UU, VV, WW, &
            CUTFACES=.FALSE.)
        CALL CC_VELOCITY_FLUX(MESHES(NM), DT, EST_FLAG, &
            RHOP, CORRECT_GRAV=.TRUE., &
