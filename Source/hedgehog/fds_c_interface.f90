FUNCTION C_FDS_CHECK_CALL_HT_1D() RESULT(CALL_HT_1D_OUT) BIND(C, NAME="fds_check_call_ht_1d")
    USE GLOBAL_CONSTANTS, ONLY: WALL_COUNTER, WALL_INCREMENT
    INTEGER(C_INT) :: CALL_HT_1D_OUT
    ! Check if we should call 1-D heat transfer (wall.f90:95-98)
    IF (.NOT.INITIALIZATION_PHASE .AND. CORRECTOR) THEN
        IF (WALL_COUNTER == WALL_INCREMENT) THEN
            CALL_HT_1D_OUT = 1
        ELSE
            CALL_HT_1D_OUT = 0
        ENDIF
    ELSE
        CALL_HT_1D_OUT = 0
    ENDIF
END FUNCTION C_FDS_CHECK_CALL_HT_1D

