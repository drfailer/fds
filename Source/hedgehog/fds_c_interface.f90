!> Thread-safe version of WALL_BC_PREPROCESSING using kernel routines.
!> Can be called from parallel kernel tasks (no POINT_TO_MESH dependency).
SUBROUTINE C_FDS_WALL_BC_PREPROCESSING_KERNEL(NM, T, DT_BC, CALL_HT_1D) &
    BIND(C, NAME="fds_wall_bc_preprocessing_kernel")
    USE WALL_KERNELS, ONLY: NEAR_SURFACE_GAS_VARIABLES_KERNEL, ASSIGN_GHOST_VALUE_KERNEL
    USE PHYSICAL_FUNCTIONS, ONLY: HEAT_TRANSFER_COEFFICIENT
    USE MESH_VARIABLES, ONLY: MESHES
    INTEGER(C_INT), VALUE :: NM, CALL_HT_1D
    REAL(C_DOUBLE), VALUE :: T, DT_BC
    LOGICAL :: HT_1D_FLAG, PRED_FLAG
    INTEGER :: IW, ITW
    TYPE(MESH_TYPE), POINTER :: M
    TYPE(WALL_TYPE), POINTER :: WC
    TYPE(THIN_WALL_TYPE), POINTER :: TW
    TYPE(SURFACE_TYPE), POINTER :: SF
    TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
    TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1

    HT_1D_FLAG = (CALL_HT_1D /= 0)
    PRED_FLAG = PREDICTOR
    M => MESHES(NM)

    DO IW=1,M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS
       WC => M%WALL(IW)
       BC => M%BOUNDARY_COORD(WC%BC_INDEX)
       B1 => M%BOUNDARY_PROP1(WC%B1_INDEX)
       IF (IW<=M%N_EXTERNAL_WALL_CELLS) CALL ASSIGN_GHOST_VALUE_KERNEL(M,IW,BC,B1,PRED_FLAG)
       IF (WC%BOUNDARY_TYPE==NULL_BOUNDARY) CYCLE
       SF => SURFACE(WC%SURF_INDEX)
       CALL NEAR_SURFACE_GAS_VARIABLES_KERNEL(M,T,SF,BC,B1,WALL_INDEX=IW)
       IF (HT_1D_FLAG .AND. SF%THERMAL_BC_INDEX==THERMALLY_THICK) &
          B1%HEAT_TRANS_COEF = HEAT_TRANSFER_COEFFICIENT(M,T,B1%TMP_G-B1%TMP_F,SF,WALL_INDEX_IN=IW)
    ENDDO

    IF (M%N_THIN_WALL_CELLS>0 .AND. HT_1D_FLAG) THEN
       DO ITW=1,M%N_THIN_WALL_CELLS
          TW => M%THIN_WALL(ITW)
          BC => M%BOUNDARY_COORD(TW%BC_INDEX)
          B1 => M%BOUNDARY_PROP1(TW%B1_INDEX)
          SF => SURFACE(TW%SURF_INDEX)
          CALL NEAR_SURFACE_GAS_VARIABLES_KERNEL(M,T,SF,BC,B1,TW=TW,THIN_WALL_INDEX=ITW)
          IF (TW%WALL_INDEX_M>0) THEN
             B1%HEAT_TRANS_COEF = HEAT_TRANSFER_COEFFICIENT(M,T,B1%TMP_G-B1%TMP_F,SF,WALL_INDEX_IN=TW%WALL_INDEX_M)
          ELSEIF (TW%WALL_INDEX_P>0) THEN
             B1%HEAT_TRANS_COEF = HEAT_TRANSFER_COEFFICIENT(M,T,B1%TMP_G-B1%TMP_F,SF,WALL_INDEX_IN=TW%WALL_INDEX_P)
          ELSE
             B1%HEAT_TRANS_COEF = 0._EB
          ENDIF
       ENDDO
    ENDIF
END SUBROUTINE C_FDS_WALL_BC_PREPROCESSING_KERNEL

