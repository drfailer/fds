FUNCTION C_FDS_ADJUST_DT(T_IN, DT_IN) RESULT(DT_OUT) BIND(C, NAME="fds_adjust_dt")
    REAL(C_DOUBLE), VALUE :: T_IN, DT_IN
    REAL(C_DOUBLE) :: DT_OUT
    DT_OUT = DT_IN
    ! Replicate the DT adjustment logic from the top of MAIN_LOOP
    IF (ALL(CHANGE_TIME_STEP_INDEX==1)) DT_OUT = MINVAL(DT_NEW)
    IF (ANY(CHANGE_TIME_STEP_INDEX==-1)) DT_OUT = MINVAL(DT_NEW)
    ! Clip final time step
    IF ((T_IN+DT_OUT+DT_END_FILL)>T_END) DT_OUT = MAX(T_END-T_IN+TWENTY_EPSILON_EB,DT_END_MINIMUM)
END FUNCTION C_FDS_ADJUST_DT

