SUBROUTINE C_FDS_CC_VELOCITY_FLUX_POST(NM, T, DT, ESTIMATED) &
    BIND(C, NAME="fds_cc_velocity_flux_post")
    USE CC_VELOCITY_KERNELS, ONLY: CUTFACE_VELOCITIES, CC_VELOCITY_FLUX
    USE MATH_FUNCTIONS, ONLY: EVALUATE_RAMP
    USE MESH_VARIABLES, ONLY: MESHES
    INTEGER(C_INT), VALUE :: NM, ESTIMATED
    REAL(C_DOUBLE), VALUE :: T, DT
    REAL(EB) :: GX(0:IBAR_MAX), GY(0:IBAR_MAX), GZ(0:IBAR_MAX)
    REAL(EB), POINTER, DIMENSION(:,:,:) :: UU, VV, WW, RHOP
    LOGICAL :: EST_FLAG
    INTEGER :: I
    TYPE(MESH_TYPE), POINTER :: M
    M => MESHES(NM)
    EST_FLAG = (ESTIMATED /= 0)
    IF (EST_FLAG) THEN
        UU => M%US; VV => M%VS; WW => M%WS; RHOP => M%RHOS
    ELSE
        UU => M%U; VV => M%V; WW => M%W; RHOP => M%RHO
    ENDIF
    ! Recompute gravity vectors (same as VELOCITY_FLUX_KERNEL)
    IF (.NOT.SPATIAL_GRAVITY_VARIATION) THEN
        GX(0:M%IBAR) = EVALUATE_RAMP(T,I_RAMP_GX)*GVEC(1)
        GY(0:M%IBAR) = EVALUATE_RAMP(T,I_RAMP_GY)*GVEC(2)
        GZ(0:M%IBAR) = EVALUATE_RAMP(T,I_RAMP_GZ)*GVEC(3)
    ELSE
        DO I=0,M%IBAR
            GX(I) = EVALUATE_RAMP(M%X(I),I_RAMP_GX)*GVEC(1)
            GY(I) = EVALUATE_RAMP(M%X(I),I_RAMP_GY)*GVEC(2)
            GZ(I) = EVALUATE_RAMP(M%X(I),I_RAMP_GZ)*GVEC(3)
        ENDDO
    ENDIF
    CALL CUTFACE_VELOCITIES(M, UU, VV, WW, CUTFACES=.FALSE.)
    CALL CC_VELOCITY_FLUX(M, DT, EST_FLAG, RHOP, &
        CORRECT_GRAV=.TRUE., GX=GX, GY=GY, GZ=GZ)
END SUBROUTINE C_FDS_CC_VELOCITY_FLUX_POST

