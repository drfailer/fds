!> MPI error reduction and velocity error file output for pressure convergence check.
SUBROUTINE C_FDS_PRESSURE_ITERATION_CHECK_CONVERGENCE(T, DT) &
    BIND(C, NAME="fds_pressure_iteration_check_convergence")
    USE COMP_FUNCTIONS, ONLY: CURRENT_TIME
    REAL(C_DOUBLE), VALUE :: T, DT
    REAL(EB) :: TNOW
    INTEGER :: NM_MAX_V, NM_MAX_P, IERR

    IF (N_MPI_PROCESSES>1) THEN
       TNOW = CURRENT_TIME()
       REAL_BUFFER_10(  1,LOWER_MESH_INDEX:UPPER_MESH_INDEX) = &
           VELOCITY_ERROR_MAX(LOWER_MESH_INDEX:UPPER_MESH_INDEX)
       REAL_BUFFER_10(  2,LOWER_MESH_INDEX:UPPER_MESH_INDEX) = &
           PRESSURE_ERROR_MAX(LOWER_MESH_INDEX:UPPER_MESH_INDEX)
       REAL_BUFFER_10(3:5,LOWER_MESH_INDEX:UPPER_MESH_INDEX) = &
           VELOCITY_ERROR_MAX_LOC(1:3,LOWER_MESH_INDEX:UPPER_MESH_INDEX)
       REAL_BUFFER_10(6:8,LOWER_MESH_INDEX:UPPER_MESH_INDEX) = &
           PRESSURE_ERROR_MAX_LOC(1:3,LOWER_MESH_INDEX:UPPER_MESH_INDEX)
       CALL MPI_ALLGATHERV(MPI_IN_PLACE,0,MPI_DATATYPE_NULL, &
                           REAL_BUFFER_10(1:10,1:NMESHES), &
                           COUNTS_10,DISPLS_10,MPI_DOUBLE_PRECISION, &
                           MPI_COMM_WORLD,IERR)
       VELOCITY_ERROR_MAX(:)         =     REAL_BUFFER_10(1,:)
       PRESSURE_ERROR_MAX(:)         =     REAL_BUFFER_10(2,:)
       VELOCITY_ERROR_MAX_LOC(1:3,:) = INT(REAL_BUFFER_10(3:5,:))
       PRESSURE_ERROR_MAX_LOC(1:3,:) = INT(REAL_BUFFER_10(6:8,:))
       T_USED(11)=T_USED(11) + CURRENT_TIME() - TNOW
    ENDIF

    IF (MY_RANK==0 .AND. VELOCITY_ERROR_FILE) THEN
       NM_MAX_V = MAXLOC(VELOCITY_ERROR_MAX,DIM=1)
       NM_MAX_P = MAXLOC(PRESSURE_ERROR_MAX,DIM=1)
       WRITE(LU_VELOCITY_ERROR, &
           '(E16.8,A,7(I7,A),E16.8,A,4(I7,A),E16.8)') &
           T,',',ICYC,',',PRESSURE_ITERATIONS,',', &
           TOTAL_PRESSURE_ITERATIONS,',', &
           NM_MAX_V,',',VELOCITY_ERROR_MAX_LOC(1,NM_MAX_V),',', &
           VELOCITY_ERROR_MAX_LOC(2,NM_MAX_V),',', &
           VELOCITY_ERROR_MAX_LOC(3,NM_MAX_V),',', &
           MAXVAL(VELOCITY_ERROR_MAX),',', &
           NM_MAX_P,',',PRESSURE_ERROR_MAX_LOC(1,NM_MAX_P),',', &
           PRESSURE_ERROR_MAX_LOC(2,NM_MAX_P),',', &
           PRESSURE_ERROR_MAX_LOC(3,NM_MAX_P),',', &
           MAXVAL(PRESSURE_ERROR_MAX)
    ENDIF

    IF (MAXVAL(PRESSURE_ERROR_MAX)<PRESSURE_TOLERANCE) &
        ITERATE_BAROCLINIC_TERM = .FALSE.
END SUBROUTINE C_FDS_PRESSURE_ITERATION_CHECK_CONVERGENCE

!> Check whether the pressure iteration loop should exit.
!> Returns 1 if converged (or max iterations reached or suspended).
FUNCTION C_FDS_PRESSURE_ITERATION_CONVERGED() RESULT(FLAG) &
    BIND(C, NAME="fds_pressure_iteration_converged")
    INTEGER(C_INT) :: FLAG
    REAL(EB), SAVE :: VELOCITY_ERROR_MAX_OLD = 0._EB
    REAL(EB), SAVE :: PRESSURE_ERROR_MAX_OLD = 0._EB

    FLAG = 0

    ! Max iterations check
    IF (PREDICTOR .AND. &
        PRESSURE_ITERATIONS>=MAX_PREDICTOR_PRESSURE_ITERATIONS) THEN
        FLAG = 1; RETURN
    ENDIF
    IF (CORRECTOR .AND. &
        PRESSURE_ITERATIONS>=MAX_PRESSURE_ITERATIONS) THEN
        FLAG = 1; RETURN
    ENDIF

    ! Tolerance check
    IF (MAXVAL(PRESSURE_ERROR_MAX)<PRESSURE_TOLERANCE .AND. &
        MAXVAL(VELOCITY_ERROR_MAX)<VELOCITY_TOLERANCE) THEN
        FLAG = 1; RETURN
    ENDIF

    ! Suspend check (stagnating convergence)
    IF (SUSPEND_PRESSURE_ITERATIONS .AND. ICYC>10) THEN
        IF (PRESSURE_ITERATIONS>3 .AND. &
            MAXVAL(VELOCITY_ERROR_MAX) > &
                ITERATION_SUSPEND_FACTOR*VELOCITY_ERROR_MAX_OLD .AND. &
            MAXVAL(PRESSURE_ERROR_MAX) > &
                ITERATION_SUSPEND_FACTOR*PRESSURE_ERROR_MAX_OLD) THEN
            FLAG = 1; RETURN
        ENDIF
        VELOCITY_ERROR_MAX_OLD = MAXVAL(VELOCITY_ERROR_MAX)
        PRESSURE_ERROR_MAX_OLD = MAXVAL(PRESSURE_ERROR_MAX)
    ENDIF
END FUNCTION C_FDS_PRESSURE_ITERATION_CONVERGED

