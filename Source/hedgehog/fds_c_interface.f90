SUBROUTINE C_FDS_UPDATE_BC_CLOCK(T) BIND(C, NAME="fds_update_bc_clock")
    USE MESH_VARIABLES, ONLY: MESHES
    REAL(C_DOUBLE), VALUE :: T
    INTEGER :: NM
    ! Update BC_CLOCK and HT_3D_SWEEP_DIRECTION (wall.f90:97-100)
    ! These are mesh-specific variables, update for all local meshes
    DO NM = LOWER_MESH_INDEX, UPPER_MESH_INDEX
        MESHES(NM)%BC_CLOCK = T
        MESHES(NM)%HT_3D_SWEEP_DIRECTION = MESHES(NM)%HT_3D_SWEEP_DIRECTION + 1
        IF (MESHES(NM)%HT_3D_SWEEP_DIRECTION > 3) MESHES(NM)%HT_3D_SWEEP_DIRECTION = 1
    ENDDO
END SUBROUTINE C_FDS_UPDATE_BC_CLOCK

