RECURSIVE SUBROUTINE C_FDS_VELOCITY_FLUX_KERNEL(NM, T, DT, &
    ESTIMATED) BIND(C, NAME="fds_velocity_flux_kernel")
    USE VELO_KERNELS, ONLY: VELOCITY_FLUX_KERNEL
    USE CC_VELOCITY_KERNELS, ONLY: CUTFACE_VELOCITIES, &
        CC_VELOCITY_FLUX
    USE MESH_VARIABLES, ONLY: MESHES
    INTEGER(C_INT), VALUE :: NM, ESTIMATED
    REAL(C_DOUBLE), VALUE :: T, DT
    LOGICAL :: EST_FLAG
