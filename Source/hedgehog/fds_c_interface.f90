    REAL(C_DOUBLE) :: DT_OUT
    DT_OUT = DT_IN
    ! Replicate the DT adjustment logic from the top of MAIN_LOOP
    IF (ALL(CHANGE_TIME_STEP_INDEX==1)) DT_OUT = MINVAL(DT_NEW)
    IF (ANY(CHANGE_TIME_STEP_INDEX==-1)) DT_OUT = MINVAL(DT_NEW)
    ! Clip final time step
