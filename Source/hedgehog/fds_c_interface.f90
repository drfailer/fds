    REAL(EB) :: GZ(0:IBAR_MAX)
    REAL(EB), POINTER, DIMENSION(:,:,:) :: UU,VV,WW,RHOP
    EST_FLAG = (ESTIMATED /= 0)
    IF (CC_IBM) THEN
