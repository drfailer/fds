                  U_TEMP(1,1,1) = UU(BC%II+1,BC%JJ,BC%KK)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,1,I_FLUX_LIMITER)
                  FX_ZZ(BC%II+1,BC%JJ,BC%KK,N) = F_TEMP(1,1,1)
               ENDIF
            CASE(-1) OFF_WALL_SELECT_2
               !            FX/UU(II-2)     ghost
               ! ... |  II-2  |  II-1  ///   II   ///
               !              ^ WALL_INDEX(II-1,-1)
               IF ((UU(BC%II-2,BC%JJ,BC%KK)<0._EB) .AND. .NOT.(M%CELL(M%CELL_INDEX(BC%II-1,BC%JJ,BC%KK))%WALL_INDEX(-1)>0)) THEN
                  Z_TEMP(1:3,1,1) = (/RHO_Z_P(BC%II-2:BC%II-1,BC%JJ,BC%KK),RHO_Z_P(BC%II-1,BC%JJ,BC%KK)/)
                  U_TEMP(1,1,1) = UU(BC%II-2,BC%JJ,BC%KK)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,1,I_FLUX_LIMITER)
                  FX_ZZ(BC%II-2,BC%JJ,BC%KK,N) = F_TEMP(1,1,1)
               ENDIF
            CASE( 2) OFF_WALL_SELECT_2
               IF ((VV(BC%II,BC%JJ+1,BC%KK)>0._EB) .AND. .NOT.(M%CELL(M%CELL_INDEX(BC%II,BC%JJ+1,BC%KK))%WALL_INDEX(+2)>0)) THEN
                  Z_TEMP(1,0:2,1) = (/RHO_Z_P(BC%II,BC%JJ+1,BC%KK),RHO_Z_P(BC%II,BC%JJ+1:BC%JJ+2,BC%KK)/)
                  U_TEMP(1,1,1) = VV(BC%II,BC%JJ+1,BC%KK)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,2,I_FLUX_LIMITER)
                  FY_ZZ(BC%II,BC%JJ+1,BC%KK,N) = F_TEMP(1,1,1)
               ENDIF
            CASE(-2) OFF_WALL_SELECT_2
               IF ((VV(BC%II,BC%JJ-2,BC%KK)<0._EB) .AND. .NOT.(M%CELL(M%CELL_INDEX(BC%II,BC%JJ-1,BC%KK))%WALL_INDEX(-2)>0)) THEN
                  Z_TEMP(1,1:3,1) = (/RHO_Z_P(BC%II,BC%JJ-2:BC%JJ-1,BC%KK),RHO_Z_P(BC%II,BC%JJ-1,BC%KK)/)
                  U_TEMP(1,1,1) = VV(BC%II,BC%JJ-2,BC%KK)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,2,I_FLUX_LIMITER)
                  FY_ZZ(BC%II,BC%JJ-2,BC%KK,N) = F_TEMP(1,1,1)
               ENDIF
            CASE( 3) OFF_WALL_SELECT_2
               IF ((WW(BC%II,BC%JJ,BC%KK+1)>0._EB) .AND. .NOT.(M%CELL(M%CELL_INDEX(BC%II,BC%JJ,BC%KK+1))%WALL_INDEX(+3)>0)) THEN
                  Z_TEMP(1,1,0:2) = (/RHO_Z_P(BC%II,BC%JJ,BC%KK+1),RHO_Z_P(BC%II,BC%JJ,BC%KK+1:BC%KK+2)/)
                  U_TEMP(1,1,1) = WW(BC%II,BC%JJ,BC%KK+1)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,3,I_FLUX_LIMITER)
                  FZ_ZZ(BC%II,BC%JJ,BC%KK+1,N) = F_TEMP(1,1,1)
               ENDIF
            CASE(-3) OFF_WALL_SELECT_2
               IF ((WW(BC%II,BC%JJ,BC%KK-2)<0._EB) .AND. .NOT.(M%CELL(M%CELL_INDEX(BC%II,BC%JJ,BC%KK-1))%WALL_INDEX(-3)>0)) THEN
                  Z_TEMP(1,1,1:3) = (/RHO_Z_P(BC%II,BC%JJ,BC%KK-2:BC%KK-1),RHO_Z_P(BC%II,BC%JJ,BC%KK-1)/)
                  U_TEMP(1,1,1) = WW(BC%II,BC%JJ,BC%KK-2)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,3,I_FLUX_LIMITER)
                  FZ_ZZ(BC%II,BC%JJ,BC%KK-2,N) = F_TEMP(1,1,1)
               ENDIF
         END SELECT OFF_WALL_SELECT_2

      ENDIF OFF_WALL_IF_2

   ENDDO WALL_LOOP_2

ENDDO SPECIES_LOOP

FACE_CORRECTION_IF: IF (FLUX_LIMITER_MW_CORRECTION) THEN

   ! Repeat the above for DENSITY

   RHO_RMW=>M%WORK_PAD

   DO K=-1,M%KBP1+1
      DO J=-1,M%JBP1+1
         DO I=-1,M%IBP1+1
            ZZ_GET(1:N_TRACKED_SPECIES) = ZZP(I,J,K,1:N_TRACKED_SPECIES)
            CALL GET_MOLECULAR_WEIGHT(ZZ_GET,MW_G)
            RHO_RMW(I,J,K) = RHOP(I,J,K)/MW_G
         ENDDO
      ENDDO
   ENDDO

   FX_P(LBOUND(FX_ZZ,1):,LBOUND(FX_ZZ,2):,LBOUND(FX_ZZ,3):) => FX_ZZ(:,:,:,0)
   FY_P(LBOUND(FY_ZZ,1):,LBOUND(FY_ZZ,2):,LBOUND(FY_ZZ,3):) => FY_ZZ(:,:,:,0)
   FZ_P(LBOUND(FZ_ZZ,1):,LBOUND(FZ_ZZ,2):,LBOUND(FZ_ZZ,3):) => FZ_ZZ(:,:,:,0)
   CALL GET_SCALAR_FACE_VALUE(UU,RHO_RMW,FX_P,0,M%IBAR,1,M%JBAR,1,M%KBAR,1,I_FLUX_LIMITER)
   CALL GET_SCALAR_FACE_VALUE(VV,RHO_RMW,FY_P,1,M%IBAR,0,M%JBAR,1,M%KBAR,2,I_FLUX_LIMITER)
   CALL GET_SCALAR_FACE_VALUE(WW,RHO_RMW,FZ_P,1,M%IBAR,1,M%JBAR,0,M%KBAR,3,I_FLUX_LIMITER)

   U_TEMP => U_WORK
   F_TEMP => F_WORK
   Z_TEMP => Z_WORK
   WALL_LOOP_3: DO IW=1,M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS
      WC=>M%WALL(IW)
      IF (WC%BOUNDARY_TYPE==NULL_BOUNDARY) CYCLE WALL_LOOP_3
      BC=>M%BOUNDARY_COORD(WC%BC_INDEX)
      B1=>M%BOUNDARY_PROP1(WC%B1_INDEX)

      ! Overwrite first off-wall advective flux if flow is away from the wall and if the face is not also a wall cell

      OFF_WALL_IF_3: IF (WC%BOUNDARY_TYPE/=INTERPOLATED_BOUNDARY .AND. WC%BOUNDARY_TYPE/=OPEN_BOUNDARY) THEN

         OFF_WALL_SELECT_3: SELECT CASE(BC%IOR)
            CASE( 1) OFF_WALL_SELECT_3
               !      ghost          FX/UU(II+1)
               ! ///   II   ///  II+1  |  II+2  | ...
               !                       ^ WALL_INDEX(II+1,+1)
               IF ((UU(BC%II+1,BC%JJ,BC%KK)>0._EB) .AND. .NOT.(M%CELL(M%CELL_INDEX(BC%II+1,BC%JJ,BC%KK))%WALL_INDEX(+1)>0)) THEN
                  Z_TEMP(0:2,1,1) = (/RHO_Z_P(BC%II+1,BC%JJ,BC%KK),RHO_Z_P(BC%II+1:BC%II+2,BC%JJ,BC%KK)/)
                  U_TEMP(1,1,1) = UU(BC%II+1,BC%JJ,BC%KK)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,1,I_FLUX_LIMITER)
                  FX_ZZ(BC%II+1,BC%JJ,BC%KK,0) = F_TEMP(1,1,1)
               ENDIF
            CASE(-1) OFF_WALL_SELECT_3
               !            FX/UU(II-2)     ghost
               ! ... |  II-2  |  II-1  ///   II   ///
               !              ^ WALL_INDEX(II-1,-1)
               IF ((UU(BC%II-2,BC%JJ,BC%KK)<0._EB) .AND. .NOT.(M%CELL(M%CELL_INDEX(BC%II-1,BC%JJ,BC%KK))%WALL_INDEX(-1)>0)) THEN
                  Z_TEMP(1:3,1,1) = (/RHO_Z_P(BC%II-2:BC%II-1,BC%JJ,BC%KK),RHO_Z_P(BC%II-1,BC%JJ,BC%KK)/)
                  U_TEMP(1,1,1) = UU(BC%II-2,BC%JJ,BC%KK)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,1,I_FLUX_LIMITER)
                  FX_ZZ(BC%II-2,BC%JJ,BC%KK,0) = F_TEMP(1,1,1)
               ENDIF
            CASE( 2) OFF_WALL_SELECT_3
               IF ((VV(BC%II,BC%JJ+1,BC%KK)>0._EB) .AND. .NOT.(M%CELL(M%CELL_INDEX(BC%II,BC%JJ+1,BC%KK))%WALL_INDEX(+2)>0)) THEN
                  Z_TEMP(1,0:2,1) = (/RHO_Z_P(BC%II,BC%JJ+1,BC%KK),RHO_Z_P(BC%II,BC%JJ+1:BC%JJ+2,BC%KK)/)
                  U_TEMP(1,1,1) = VV(BC%II,BC%JJ+1,BC%KK)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,2,I_FLUX_LIMITER)
                  FY_ZZ(BC%II,BC%JJ+1,BC%KK,0) = F_TEMP(1,1,1)
               ENDIF
            CASE(-2) OFF_WALL_SELECT_3
               IF ((VV(BC%II,BC%JJ-2,BC%KK)<0._EB) .AND. .NOT.(M%CELL(M%CELL_INDEX(BC%II,BC%JJ-1,BC%KK))%WALL_INDEX(-2)>0)) THEN
                  Z_TEMP(1,1:3,1) = (/RHO_Z_P(BC%II,BC%JJ-2:BC%JJ-1,BC%KK),RHO_Z_P(BC%II,BC%JJ-1,BC%KK)/)
                  U_TEMP(1,1,1) = VV(BC%II,BC%JJ-2,BC%KK)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,2,I_FLUX_LIMITER)
                  FY_ZZ(BC%II,BC%JJ-2,BC%KK,0) = F_TEMP(1,1,1)
               ENDIF
            CASE( 3) OFF_WALL_SELECT_3
               IF ((WW(BC%II,BC%JJ,BC%KK+1)>0._EB) .AND. .NOT.(M%CELL(M%CELL_INDEX(BC%II,BC%JJ,BC%KK+1))%WALL_INDEX(+3)>0)) THEN
                  Z_TEMP(1,1,0:2) = (/RHO_Z_P(BC%II,BC%JJ,BC%KK+1),RHO_Z_P(BC%II,BC%JJ,BC%KK+1:BC%KK+2)/)
                  U_TEMP(1,1,1) = WW(BC%II,BC%JJ,BC%KK+1)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,3,I_FLUX_LIMITER)
                  FZ_ZZ(BC%II,BC%JJ,BC%KK+1,0) = F_TEMP(1,1,1)
               ENDIF
            CASE(-3) OFF_WALL_SELECT_3
               IF ((WW(BC%II,BC%JJ,BC%KK-2)<0._EB) .AND. .NOT.(M%CELL(M%CELL_INDEX(BC%II,BC%JJ,BC%KK-1))%WALL_INDEX(-3)>0)) THEN
                  Z_TEMP(1,1,1:3) = (/RHO_Z_P(BC%II,BC%JJ,BC%KK-2:BC%KK-1),RHO_Z_P(BC%II,BC%JJ,BC%KK-1)/)
                  U_TEMP(1,1,1) = WW(BC%II,BC%JJ,BC%KK-2)
                  CALL GET_SCALAR_FACE_VALUE(U_TEMP,Z_TEMP,F_TEMP,1,1,1,1,1,1,3,I_FLUX_LIMITER)
                  FZ_ZZ(BC%II,BC%JJ,BC%KK-2,0) = F_TEMP(1,1,1)
               ENDIF
         END SELECT OFF_WALL_SELECT_3

      ENDIF OFF_WALL_IF_3

   ENDDO WALL_LOOP_3

   ! Now correct the max face value of (RHO*ZZ) such that SUM(RHO*ZZ/MW)_FACE = RHO_FACE/MW_FACE
   ! (necessary condition to preserve isothermal flow)

   DO K=0,M%KBAR
      DO J=0,M%JBAR
         DO I=0,M%IBAR
   N=MAXLOC(FX_ZZ(I,J,K,1:N_TRACKED_SPECIES),1)
   MW_G = SPECIES_MIXTURE(N)%MW
   FX_ZZ(I,J,K,N) = MW_G*MAX( 0._EB, FX_ZZ(I,J,K,0) &
         - SUM(FX_ZZ(I,J,K,1:(N-1))/SPECIES_MIXTURE(1:(N-1))%MW) &
         - SUM(FX_ZZ(I,J,K,(N+1):N_TRACKED_SPECIES)/SPECIES_MIXTURE((N+1):N_TRACKED_SPECIES)%MW) )
   N=MAXLOC(FY_ZZ(I,J,K,1:N_TRACKED_SPECIES),1)
   MW_G = SPECIES_MIXTURE(N)%MW
   FY_ZZ(I,J,K,N) = MW_G*MAX( 0._EB, FY_ZZ(I,J,K,0) &
         - SUM(FY_ZZ(I,J,K,1:(N-1))/SPECIES_MIXTURE(1:(N-1))%MW) &
         - SUM(FY_ZZ(I,J,K,(N+1):N_TRACKED_SPECIES)/SPECIES_MIXTURE((N+1):N_TRACKED_SPECIES)%MW) )
   N=MAXLOC(FZ_ZZ(I,J,K,1:N_TRACKED_SPECIES),1)
   MW_G = SPECIES_MIXTURE(N)%MW
   FZ_ZZ(I,J,K,N) = MW_G*MAX( 0._EB, FZ_ZZ(I,J,K,0) &
         - SUM(FZ_ZZ(I,J,K,1:(N-1))/SPECIES_MIXTURE(1:(N-1))%MW) &
         - SUM(FZ_ZZ(I,J,K,(N+1):N_TRACKED_SPECIES)/SPECIES_MIXTURE((N+1):N_TRACKED_SPECIES)%MW) )
         ENDDO
      ENDDO
   ENDDO

ENDIF FACE_CORRECTION_IF

END SUBROUTINE SPECIES_ADVECTION_PART_1_NEW



SUBROUTINE SPECIES_ADVECTION_PART_2(N,U_DOT_DEL_RHO_Z)

INTEGER, INTENT(IN) :: N
REAL(EB), POINTER, DIMENSION(:,:,:) :: U_DOT_DEL_RHO_Z
REAL(EB), POINTER, DIMENSION(:,:,:,:) :: FX_ZZ,FY_ZZ,FZ_ZZ
REAL(EB) :: UN,DU_P,DU_M,DV_P,DV_M,DW_P,DW_M,DU
INTEGER :: IC,I,J,K,IW
TYPE(WALL_TYPE), POINTER :: WC
TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1

FX_ZZ=>M%SWORK1
FY_ZZ=>M%SWORK2
FZ_ZZ=>M%SWORK3
U_DOT_DEL_RHO_Z=>M%WORK7 ; U_DOT_DEL_RHO_Z = 0._EB

WALL_LOOP: DO IW=1,M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS

   WC=>M%WALL(IW)
   IF (WC%BOUNDARY_TYPE==NULL_BOUNDARY) CYCLE WALL_LOOP
   B1 => M%BOUNDARY_PROP1(WC%B1_INDEX)
   BC => M%BOUNDARY_COORD(WC%BC_INDEX)

   ! Correct flux terms at the boundary

   SELECT CASE(WC%BOUNDARY_TYPE)
      CASE DEFAULT
         IOR_SELECT: SELECT CASE(BC%IOR)
            CASE( 1); UN = UU(BC%II  ,BC%JJ  ,BC%KK  )
            CASE(-1); UN = UU(BC%II-1,BC%JJ  ,BC%KK  )
            CASE( 2); UN = VV(BC%II  ,BC%JJ  ,BC%KK  )
            CASE(-2); UN = VV(BC%II  ,BC%JJ-1,BC%KK  )
            CASE( 3); UN = WW(BC%II  ,BC%JJ  ,BC%KK  )
            CASE(-3); UN = WW(BC%II  ,BC%JJ  ,BC%KK-1)
         END SELECT IOR_SELECT
      CASE(SOLID_BOUNDARY)
         IF (PREDICTOR) UN = -SIGN(1._EB,REAL(BC%IOR,EB))*B1%U_NORMAL_S
         IF (CORRECTOR) UN = -SIGN(1._EB,REAL(BC%IOR,EB))*B1%U_NORMAL
      CASE(INTERPOLATED_BOUNDARY)
         UN = M%UVW_SAVE(IW)
   END SELECT

   DU = (B1%RHO_F*B1%ZZ_F(N) - RHOP(BC%IIG,BC%JJG,BC%KKG)*ZZP(BC%IIG,BC%JJG,BC%KKG,N))*UN
   U_DOT_DEL_RHO_Z(BC%IIG,BC%JJG,BC%KKG) = U_DOT_DEL_RHO_Z(BC%IIG,BC%JJG,BC%KKG) - SIGN(1._EB,REAL(BC%IOR,EB))*DU*B1%RDN

ENDDO WALL_LOOP

DO K=1,M%KBAR
   DO J=1,M%JBAR
      DO I=1,M%IBAR
IC = M%CELL_INDEX(I,J,K)
IF (M%CELL(IC)%SOLID) CYCLE
DU_P = 0._EB
DU_M = 0._EB
DV_P = 0._EB
DV_M = 0._EB
DW_P = 0._EB
DW_M = 0._EB
IF (M%CELL(IC)%WALL_INDEX( 1)==0) DU_P = (FX_ZZ(I,J,K,N)   - RHOP(I,J,K)*ZZP(I,J,K,N))*UU(I,J,K)
IF (M%CELL(IC)%WALL_INDEX(-1)==0) DU_M = (FX_ZZ(I-1,J,K,N) - RHOP(I,J,K)*ZZP(I,J,K,N))*UU(I-1,J,K)
IF (M%CELL(IC)%WALL_INDEX( 2)==0) DV_P = (FY_ZZ(I,J,K,N)   - RHOP(I,J,K)*ZZP(I,J,K,N))*VV(I,J,K)
IF (M%CELL(IC)%WALL_INDEX(-2)==0) DV_M = (FY_ZZ(I,J-1,K,N) - RHOP(I,J,K)*ZZP(I,J,K,N))*VV(I,J-1,K)
IF (M%CELL(IC)%WALL_INDEX( 3)==0) DW_P = (FZ_ZZ(I,J,K,N)   - RHOP(I,J,K)*ZZP(I,J,K,N))*WW(I,J,K)
IF (M%CELL(IC)%WALL_INDEX(-3)==0) DW_M = (FZ_ZZ(I,J,K-1,N) - RHOP(I,J,K)*ZZP(I,J,K,N))*WW(I,J,K-1)
U_DOT_DEL_RHO_Z(I,J,K) = U_DOT_DEL_RHO_Z(I,J,K) &
   + (DU_P-DU_M)*M%RDX(I) + (DV_P-DV_M)*M%RDY(J) + (DW_P-DW_M)*M%RDZ(K)
      ENDDO
   ENDDO
ENDDO

END SUBROUTINE SPECIES_ADVECTION_PART_2


SUBROUTINE MERGE_PRESSURE_ZONES

INTEGER :: IW,IPZ,IOPZ
TYPE(WALL_TYPE), POINTER :: WC
TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC

DO IW=1,M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS
   WC=>M%WALL(IW)
   IF (WC%BOUNDARY_TYPE/=NULL_BOUNDARY .AND. WC%BOUNDARY_TYPE/=OPEN_BOUNDARY .AND. WC%BOUNDARY_TYPE/=INTERPOLATED_BOUNDARY) CYCLE
   BC => M%BOUNDARY_COORD(WC%BC_INDEX)
   IF (M%CELL(M%CELL_INDEX(BC%IIG,BC%JJG,BC%KKG))%SOLID) CYCLE
   IPZ  = M%PRESSURE_ZONE(BC%IIG,BC%JJG,BC%KKG)
   IOPZ = M%PRESSURE_ZONE(BC%II,BC%JJ,BC%KK)
   IF (IW>M%N_EXTERNAL_WALL_CELLS .AND. IPZ/=IOPZ) THEN
      CONNECTED_ZONES(IOPZ,IPZ) = 1
      CONNECTED_ZONES(IPZ,IOPZ) = 1
   ENDIF
   IF (WC%BOUNDARY_TYPE==OPEN_BOUNDARY) THEN
      CONNECTED_ZONES(0,IPZ) = 1
      CONNECTED_ZONES(IPZ,0) = 1
   ELSEIF (WC%BOUNDARY_TYPE==INTERPOLATED_BOUNDARY) THEN
      CONNECTED_ZONES(IOPZ,IPZ) = 1
      CONNECTED_ZONES(IPZ,IOPZ) = 1
   ENDIF
ENDDO

END SUBROUTINE MERGE_PRESSURE_ZONES


SUBROUTINE PREDICT_NORMAL_VELOCITY(IW,T,DT)

USE MATH_FUNCTIONS, ONLY: EVALUATE_RAMP
INTEGER, INTENT(IN) :: IW
REAL(EB), INTENT(IN) :: T,DT
REAL(EB) :: TSI,TIME_RAMP_FACTOR,PROFILE_FACTOR
TYPE(VENTS_TYPE), POINTER :: VT
TYPE(SURFACE_TYPE), POINTER :: SF
TYPE(WALL_TYPE), POINTER :: WC
TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1

WC => M%WALL(IW)
BC => M%BOUNDARY_COORD(WC%BC_INDEX)
B1 => M%BOUNDARY_PROP1(WC%B1_INDEX)
SF => SURFACE(WC%SURF_INDEX)

PREDICT_NORMALS: IF (PREDICTOR) THEN

   WALL_CELL_TYPE: SELECT CASE (WC%BOUNDARY_TYPE)

      CASE (NULL_BOUNDARY)

         B1%U_NORMAL_S = 0._EB

      CASE (SOLID_BOUNDARY)

         IF (SF%SPECIES_BC_INDEX==SPECIFIED_MASS_FLUX .OR. SF%SPECIES_BC_INDEX==INTERPOLATED_BC .OR. &
             B1%NODE_INDEX > 0 .OR. ANY(SF%LEAK_PATH>0)) EXIT WALL_CELL_TYPE

         IF (ABS(B1%T_IGN-T_BEGIN) < SPACING(B1%T_IGN) .AND. SF%RAMP(TIME_VELO)%INDEX>=1) THEN
            TSI = T + DT
         ELSE
            TSI = T + DT - B1%T_IGN
            IF (TSI<0._EB) THEN
               B1%U_NORMAL_S = 0._EB
               EXIT WALL_CELL_TYPE
            ENDIF
         ENDIF
         TIME_RAMP_FACTOR = EVALUATE_RAMP(TSI,SF%RAMP(TIME_VELO)%INDEX,TAU=SF%RAMP(TIME_VELO)%TAU)
         B1%U_NORMAL_S = TIME_RAMP_FACTOR*B1%U_NORMAL_0

         ! Special Cases
         NEUMANN_IF: IF (SF%SPECIFIED_NORMAL_GRADIENT) THEN
            SELECT CASE(BC%IOR)
               CASE( 1); B1%U_NORMAL_S =-(M%U(BC%IIG,BC%JJG,BC%KKG)   + SF%VEL_GRAD*B1%RDN)
               CASE(-1); B1%U_NORMAL_S = (M%U(BC%IIG-1,BC%JJG,BC%KKG) + SF%VEL_GRAD*B1%RDN)
               CASE( 2); B1%U_NORMAL_S =-(M%V(BC%IIG,BC%JJG,BC%KKG)   + SF%VEL_GRAD*B1%RDN)
               CASE(-2); B1%U_NORMAL_S = (M%V(BC%IIG,BC%JJG-1,BC%KKG) + SF%VEL_GRAD*B1%RDN)
               CASE( 3); B1%U_NORMAL_S =-(M%W(BC%IIG,BC%JJG,BC%KKG)   + SF%VEL_GRAD*B1%RDN)
               CASE(-3); B1%U_NORMAL_S = (M%W(BC%IIG,BC%JJG,BC%KKG-1) + SF%VEL_GRAD*B1%RDN)
            END SELECT
         ENDIF NEUMANN_IF
         IF (ABS(SURFACE(WC%SURF_INDEX)%MASS_FLUX_TOTAL)>=TWENTY_EPSILON_EB) B1%U_NORMAL_S = &
                                                                          B1%U_NORMAL_S*RHOA/B1%RHO_F
         VENT_IF: IF (WC%VENT_INDEX>0) THEN
            VT=>M%VENTS(WC%VENT_INDEX)
            IF (VT%N_EDDY>0) THEN ! Synthetic Eddy Method
               IF (SF%PROFILE/=0 .AND. ABS(SF%VEL)>TWENTY_EPSILON_EB) THEN
                  PROFILE_FACTOR = ABS(B1%U_NORMAL_0/SF%VEL)
               ELSE
                  PROFILE_FACTOR = 1._EB
               ENDIF
               SELECT CASE(BC%IOR)
                  CASE( 1); B1%U_NORMAL_S = B1%U_NORMAL_S - TIME_RAMP_FACTOR*VT%U_EDDY(BC%JJ,BC%KK)*PROFILE_FACTOR
                  CASE(-1); B1%U_NORMAL_S = B1%U_NORMAL_S + TIME_RAMP_FACTOR*VT%U_EDDY(BC%JJ,BC%KK)*PROFILE_FACTOR
                  CASE( 2); B1%U_NORMAL_S = B1%U_NORMAL_S - TIME_RAMP_FACTOR*VT%V_EDDY(BC%II,BC%KK)*PROFILE_FACTOR
                  CASE(-2); B1%U_NORMAL_S = B1%U_NORMAL_S + TIME_RAMP_FACTOR*VT%V_EDDY(BC%II,BC%KK)*PROFILE_FACTOR
                  CASE( 3); B1%U_NORMAL_S = B1%U_NORMAL_S - TIME_RAMP_FACTOR*VT%W_EDDY(BC%II,BC%JJ)*PROFILE_FACTOR
                  CASE(-3); B1%U_NORMAL_S = B1%U_NORMAL_S + TIME_RAMP_FACTOR*VT%W_EDDY(BC%II,BC%JJ)*PROFILE_FACTOR
               END SELECT
            ENDIF
         ENDIF VENT_IF

      CASE(OPEN_BOUNDARY,INTERPOLATED_BOUNDARY)
         SELECT CASE(BC%IOR)
            CASE( 1); B1%U_NORMAL_S = -M%U(BC%II,BC%JJ,BC%KK)
            CASE(-1); B1%U_NORMAL_S =  M%U(BC%II-1,BC%JJ,BC%KK)
            CASE( 2); B1%U_NORMAL_S = -M%V(BC%II,BC%JJ,BC%KK)
            CASE(-2); B1%U_NORMAL_S =  M%V(BC%II,BC%JJ-1,BC%KK)
            CASE( 3); B1%U_NORMAL_S = -M%W(BC%II,BC%JJ,BC%KK)
            CASE(-3); B1%U_NORMAL_S =  M%W(BC%II,BC%JJ,BC%KK-1)
         END SELECT

   END SELECT WALL_CELL_TYPE

   ! Calculate du/dt, dv/dt, dw/dt at external boundaries. DUNDT is only used for Neumann BCs.

   IF (IW<=M%N_EXTERNAL_WALL_CELLS) M%EXTERNAL_WALL(IW)%DUNDT = (B1%U_NORMAL_S-B1%U_NORMAL)/DT

ELSE PREDICT_NORMALS

   ! In the CORRECTOR step, the normal component of velocity, U_NORMAL, is the same as the predicted value, U_NORMAL_S.
   ! However, for species mass fluxes and HVAC, U_NORMAL is computed elsewhere (wall.f90).

   IF (WC%BOUNDARY_TYPE/=SOLID_BOUNDARY .OR. (SF%SPECIES_BC_INDEX/=SPECIFIED_MASS_FLUX .AND. &
       SF%SPECIES_BC_INDEX/=INTERPOLATED_BC .AND. B1%NODE_INDEX<=0 .AND. ALL(SF%LEAK_PATH<=0))) B1%U_NORMAL = B1%U_NORMAL_S

   ! Calculate du/dt, dv/dt, dw/dt at external boundaries. DUNDT is only used for Neumann BCs. Note the second-order RK formula.

   IF (IW<=M%N_EXTERNAL_WALL_CELLS) M%EXTERNAL_WALL(IW)%DUNDT = M%EXTERNAL_WALL(IW)%DUNDT + 2._EB*(B1%U_NORMAL-B1%U_NORMAL_S)/DT

ENDIF PREDICT_NORMALS

END SUBROUTINE PREDICT_NORMAL_VELOCITY


END SUBROUTINE DIVERGENCE_PART_1_KERNEL


!> \brief Add QR (radiation source term) to the divergence DP.
!> Used after DIVERGENCE_PART_1_KERNEL(SKIP_QR=.TRUE.) and a QR exchange.
!> \param M Mesh data structure
!> \param NM Mesh number

RECURSIVE SUBROUTINE DIVERGENCE_PART_1_ADD_QR_KERNEL(M,NM)

TYPE(MESH_TYPE), INTENT(INOUT), TARGET :: M
INTEGER, INTENT(IN) :: NM
REAL(EB), POINTER, DIMENSION(:,:,:) :: DP
INTEGER :: I,J,K

IF (SOLID_PHASE_ONLY) RETURN

SELECT CASE(PREDICTOR)
   CASE(.TRUE.)
      DP => M%DS
   CASE(.FALSE.)
      DP => M%D
END SELECT

SELECT CASE(CYLINDRICAL)
CASE(.FALSE.)
   DO K=1,M%KBAR
      DO J=1,M%JBAR
         DO I=1,M%IBAR
            DP(I,J,K) = DP(I,J,K) + M%QR(I,J,K)
         ENDDO
      ENDDO
   ENDDO
CASE(.TRUE.)
   DO K=1,M%KBAR
      DO J=1,M%JBAR
         DO I=1,M%IBAR
            DP(I,J,K) = DP(I,J,K) + M%QR(I,J,K)
         ENDDO
      ENDDO
   ENDDO
END SELECT

END SUBROUTINE DIVERGENCE_PART_1_ADD_QR_KERNEL


!> \brief Finish computing the divergence of the flow, D, and then compute its time derivative, DDDT
!> \param M Mesh data structure
!> \param DT Time step (s)
!> \param NM Mesh number

SUBROUTINE DIVERGENCE_PART_2_KERNEL(M,DT,NM)

USE COMPLEX_GEOMETRY, ONLY : CC_CGSC, CC_UNKZ, CC_SOLID, CC_CUTCFE
USE CC_PRESSURE_KERNELS, ONLY : ADD_CUTCELL_D_PBAR_DT, &
   ADD_LINKEDCELL_D_PBAR_DT
USE CC_PRESSURE, ONLY : GET_CUTCELL_DDDT
USE CC_VELOCITY, ONLY : GET_LINKED_VELOCITIES

TYPE(MESH_TYPE), INTENT(INOUT), TARGET :: M
INTEGER, INTENT(IN) :: NM
REAL(EB), INTENT(IN) :: DT
REAL(EB), POINTER, DIMENSION(:,:,:) :: DP,RTRM,DIV
REAL(EB) :: USUM_ADD(N_ZONE),UN_P
REAL(EB) :: RDT,P_EQ,SUM_P_PSUM,SUM_USUM,SUM_DSUM,SUM_PSUM
LOGICAL :: OPEN_ZONE
REAL(EB), POINTER, DIMENSION(:) :: D_PBAR_DT_P
REAL(EB), POINTER, DIMENSION(:,:) :: PBAR_P
INTEGER :: IW,IC,I,J,K,IPZ,IOPZ
TYPE(WALL_TYPE), POINTER :: WC
TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1

IF (SOLID_PHASE_ONLY) RETURN
IF (PERIODIC_TEST==3) RETURN
IF (PERIODIC_TEST==4) RETURN

RDT = 1._EB/DT

SELECT CASE(PREDICTOR)
   CASE(.TRUE.)
      DP => M%DS
      PBAR_P => M%PBAR_S
   CASE(.FALSE.)
      DP => M%D
      PBAR_P => M%PBAR
END SELECT

M%R_PBAR = 1._EB/PBAR_P

RTRM => M%WORK1

! Adjust volume flows (USUM) of pressure ZONEs that are connected to equalize background pressure

USUM_ADD = 0._EB

DO IPZ=1,N_ZONE
   SUM_P_PSUM = PBAR_P(1,IPZ)*PSUM(IPZ)
   OPEN_ZONE  = .FALSE.
   SUM_USUM = USUM(IPZ)
   SUM_DSUM = DSUM(IPZ)
   SUM_PSUM = PSUM(IPZ)
   DO IOPZ=N_ZONE,0,-1
      IF (IOPZ==IPZ) CYCLE
      IF (CONNECTED_ZONES(IPZ,IOPZ)>0) THEN
         IF (IOPZ==0) THEN
            OPEN_ZONE = .TRUE.
         ELSE
            SUM_P_PSUM = SUM_P_PSUM + PBAR_P(1,IOPZ)*PSUM(IOPZ)
            SUM_USUM = SUM_USUM + USUM(IOPZ)
            SUM_DSUM = SUM_DSUM + DSUM(IOPZ)
            SUM_PSUM = SUM_PSUM + PSUM(IOPZ)
         ENDIF
      ENDIF
   ENDDO
   IF (OPEN_ZONE) THEN
      P_EQ          = M%P_0(1)
      USUM_ADD(IPZ) = PSUM(IPZ)*(PBAR_P(1,IPZ)-P_EQ)/PRESSURE_RELAX_TIME + DSUM(IPZ) - USUM(IPZ)
   ELSE
      P_EQ          = SUM_P_PSUM/SUM_PSUM
      USUM_ADD(IPZ) = PSUM(IPZ)*(PBAR_P(1,IPZ)-P_EQ)/PRESSURE_RELAX_TIME + DSUM(IPZ) - USUM(IPZ) - &
                      PSUM(IPZ)*(SUM_DSUM-SUM_USUM)/SUM_PSUM
   ENDIF
ENDDO

DO IPZ=1,N_ZONE
   USUM(IPZ) = USUM(IPZ) + USUM_ADD(IPZ)
ENDDO

! Compute dP/dt for each pressure ZONE

IF_PRESSURE_ZONES: IF (N_ZONE>0) THEN

   IF (PREDICTOR) D_PBAR_DT_P => M%D_PBAR_DT_S
   IF (CORRECTOR) D_PBAR_DT_P => M%D_PBAR_DT

   ! Compute change in background pressure

   DO IPZ=1,N_ZONE
      IF (ABS(PSUM(IPZ)) > TWENTY_EPSILON_EB) D_PBAR_DT_P(IPZ) = (DSUM(IPZ) - USUM(IPZ))/PSUM(IPZ)
      IF (CORRECTOR) P_ZONE(IPZ)%DPSTAR =  D_PBAR_DT_P(IPZ)
   ENDDO

   ! Add pressure derivative to divergence

   DO K=1,M%KBAR
      DO J=1,M%JBAR
         DO I=1,M%IBAR
            IPZ = M%PRESSURE_ZONE(I,J,K)
            IF (IPZ<1) CYCLE
            IF (M%CELL(M%CELL_INDEX(I,J,K))%SOLID) CYCLE
            IF (CC_IBM) THEN
               IF (M%CCVAR(I,J,K,CC_CGSC) == CC_SOLID) THEN
                  CYCLE
               ELSEIF(M%CCVAR(I,J,K,CC_CGSC) == CC_CUTCFE) THEN
                  CALL ADD_CUTCELL_D_PBAR_DT(M,I,J,K, &
                     PBAR_P(K,IPZ), &
                     D_PBAR_DT_P(IPZ)); CYCLE
               ELSEIF(M%CCVAR(I,J,K,CC_UNKZ) > 0) THEN
                  CALL ADD_LINKEDCELL_D_PBAR_DT(M,I,J,K, &
                     PBAR_P(K,IPZ), &
                     D_PBAR_DT_P(IPZ), &
                     RTRM(I,J,K),DP(I,J,K)); CYCLE
               ENDIF
            ENDIF
            DP(I,J,K) = DP(I,J,K) - (M%R_PBAR(K,IPZ)-RTRM(I,J,K))*D_PBAR_DT_P(IPZ)
         ENDDO
      ENDDO
   ENDDO

ENDIF IF_PRESSURE_ZONES

! Zero out divergence in solid cells

SOLID_LOOP: DO IC=1,CELL_COUNT(NM)
   IF (.NOT.M%CELL(IC)%SOLID) CYCLE SOLID_LOOP
   I = M%CELL(IC)%I
   J = M%CELL(IC)%J
   K = M%CELL(IC)%K
   DP(I,J,K) = 0._EB
ENDDO SOLID_LOOP

! Zero out CC_IBM solid cells:
IF (CC_IBM) THEN
   DO K=1,M%KBAR
      DO J=1,M%JBAR
         DO I=1,M%IBAR
            IF (M%CCVAR(I,J,K,CC_CGSC) /= CC_SOLID) CYCLE
            DP(I,J,K) = 0._EB
         ENDDO
      ENDDO
   ENDDO
   CALL GET_LINKED_VELOCITIES(NM,CORRECTOR,CMP_FLG=.FALSE.)
ENDIF

! Specify divergence in boundary cells to account for volume being generated at the walls

BC_LOOP: DO IW=1,M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS
   WC => M%WALL(IW)
   IF (WC%BOUNDARY_TYPE==NULL_BOUNDARY) CYCLE BC_LOOP
   BC=>M%BOUNDARY_COORD(WC%BC_INDEX)
   SELECT CASE (WC%BOUNDARY_TYPE)
      CASE (SOLID_BOUNDARY)
         IF (.NOT.M%CELL(M%CELL_INDEX(BC%II,BC%JJ,BC%KK))%SOLID) CYCLE BC_LOOP
         B1 => M%BOUNDARY_PROP1(WC%BC_INDEX)
         IF (PREDICTOR) THEN
            UN_P = B1%U_NORMAL_S
         ELSE
            UN_P = B1%U_NORMAL
         ENDIF
         SELECT CASE(BC%IOR)
            CASE( 1)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDX(BC%II)*M%RRN(BC%II)*M%R(BC%II)
            CASE(-1)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDX(BC%II)*M%RRN(BC%II)*M%R(BC%II-1)
            CASE( 2)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDY(BC%JJ)
            CASE(-2)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDY(BC%JJ)
            CASE( 3)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDZ(BC%KK)
            CASE(-3)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDZ(BC%KK)
         END SELECT
      CASE (OPEN_BOUNDARY,MIRROR_BOUNDARY,INTERPOLATED_BOUNDARY)
         DP(BC%II,BC%JJ,BC%KK) = DP(BC%IIG,BC%JJG,BC%KKG)
   END SELECT
ENDDO BC_LOOP

! Compute time derivative of the divergence, dD/dt

DIV=>M%WORK1

IF (PREDICTOR) THEN
   DO K = 1,M%KBAR
      DO J = 1,M%JBAR
         DO I = 1,M%IBAR
            DIV(I,J,K) = (M%R(I)*M%U(I,J,K)-M%R(I-1)*M%U(I-1,J,K))*M%RDX(I)*M%RRN(I) + (M%V(I,J,K)-M%V(I,J-1,K))*M%RDY(J) + &
                         (M%W(I,J,K)-M%W(I,J,K-1))*M%RDZ(K)
         ENDDO
      ENDDO
   ENDDO
   M%DDDT = (DP-DIV)*RDT
ELSEIF (CORRECTOR) THEN
   DO K = 1,M%KBAR
      DO J = 1,M%JBAR
         DO I = 1,M%IBAR
            DIV(I,J,K) = (M%R(I)*M%U(I,J,K) -M%R(I-1)*M%U(I-1,J,K)) *M%RDX(I)*M%RRN(I) + (M%V(I,J,K)- M%V(I,J-1,K)) *M%RDY(J) + &
                         (M%W(I,J,K) -M%W(I,J,K-1)) *M%RDZ(K) &
                       + (M%R(I)*M%US(I,J,K)-M%R(I-1)*M%US(I-1,J,K))*M%RDX(I)*M%RRN(I) + (M%VS(I,J,K)-M%VS(I,J-1,K))*M%RDY(J) + &
                         (M%WS(I,J,K)-M%WS(I,J,K-1))*M%RDZ(K)
         ENDDO
      ENDDO
   ENDDO
   M%DDDT = (2._EB*DP-DIV)*RDT
ENDIF

IF(CC_IBM) CALL GET_CUTCELL_DDDT(DT,NM)

END SUBROUTINE DIVERGENCE_PART_2_KERNEL


!> \brief Preprocessing for DIVERGENCE_PART_2 block decomposition.
!> Computes zone operations (USUM_ADD, D_PBAR_DT_P) and R_PBAR.
!> Must be called sequentially per mesh BEFORE block kernel dispatch.
!> \param M Mesh data structure
!> \param DT Time step (s)
!> \param NM Mesh number

RECURSIVE SUBROUTINE DIVERGENCE_PART_2_PREPROCESSING(M,DT,NM)

USE COMPLEX_GEOMETRY, ONLY : CC_CGSC, CC_UNKZ, CC_SOLID, CC_CUTCFE
USE CC_VELOCITY, ONLY : GET_LINKED_VELOCITIES

TYPE(MESH_TYPE), INTENT(INOUT), TARGET :: M
INTEGER, INTENT(IN) :: NM
REAL(EB), INTENT(IN) :: DT
REAL(EB) :: USUM_ADD(N_ZONE),RDT,P_EQ,SUM_P_PSUM,SUM_USUM,SUM_DSUM,SUM_PSUM
LOGICAL :: OPEN_ZONE
REAL(EB), POINTER, DIMENSION(:) :: D_PBAR_DT_P
REAL(EB), POINTER, DIMENSION(:,:) :: PBAR_P
INTEGER :: IPZ,IOPZ

IF (SOLID_PHASE_ONLY) RETURN
IF (PERIODIC_TEST==3) RETURN
IF (PERIODIC_TEST==4) RETURN

RDT = 1._EB/DT

SELECT CASE(PREDICTOR)
   CASE(.TRUE.)
      PBAR_P => M%PBAR_S
   CASE(.FALSE.)
      PBAR_P => M%PBAR
END SELECT

M%R_PBAR = 1._EB/PBAR_P

! Adjust volume flows (USUM) of pressure ZONEs that are connected to equalize background pressure

USUM_ADD = 0._EB

DO IPZ=1,N_ZONE
   SUM_P_PSUM = PBAR_P(1,IPZ)*PSUM(IPZ)
   OPEN_ZONE  = .FALSE.
   SUM_USUM = USUM(IPZ)
   SUM_DSUM = DSUM(IPZ)
   SUM_PSUM = PSUM(IPZ)
   DO IOPZ=N_ZONE,0,-1
      IF (IOPZ==IPZ) CYCLE
      IF (CONNECTED_ZONES(IPZ,IOPZ)>0) THEN
         IF (IOPZ==0) THEN
            OPEN_ZONE = .TRUE.
         ELSE
            SUM_P_PSUM = SUM_P_PSUM + PBAR_P(1,IOPZ)*PSUM(IOPZ)
            SUM_USUM = SUM_USUM + USUM(IOPZ)
            SUM_DSUM = SUM_DSUM + DSUM(IOPZ)
            SUM_PSUM = SUM_PSUM + PSUM(IOPZ)
         ENDIF
      ENDIF
   ENDDO
   IF (OPEN_ZONE) THEN
      P_EQ          = M%P_0(1)
      USUM_ADD(IPZ) = PSUM(IPZ)*(PBAR_P(1,IPZ)-P_EQ)/PRESSURE_RELAX_TIME + DSUM(IPZ) - USUM(IPZ)
   ELSE
      P_EQ          = SUM_P_PSUM/SUM_PSUM
      USUM_ADD(IPZ) = PSUM(IPZ)*(PBAR_P(1,IPZ)-P_EQ)/PRESSURE_RELAX_TIME + DSUM(IPZ) - USUM(IPZ) - &
                      PSUM(IPZ)*(SUM_DSUM-SUM_USUM)/SUM_PSUM
   ENDIF
ENDDO

DO IPZ=1,N_ZONE
   USUM(IPZ) = USUM(IPZ) + USUM_ADD(IPZ)
ENDDO

! Compute dP/dt for each pressure ZONE

IF (N_ZONE>0) THEN

   IF (PREDICTOR) D_PBAR_DT_P => M%D_PBAR_DT_S
   IF (CORRECTOR) D_PBAR_DT_P => M%D_PBAR_DT

   DO IPZ=1,N_ZONE
      IF (ABS(PSUM(IPZ)) > TWENTY_EPSILON_EB) D_PBAR_DT_P(IPZ) = (DSUM(IPZ) - USUM(IPZ))/PSUM(IPZ)
      IF (CORRECTOR) P_ZONE(IPZ)%DPSTAR =  D_PBAR_DT_P(IPZ)
   ENDDO

ENDIF

! CC_IBM: compute linked velocities
IF (CC_IBM) CALL GET_LINKED_VELOCITIES(NM,CORRECTOR,CMP_FLG=.FALSE.)

END SUBROUTINE DIVERGENCE_PART_2_PREPROCESSING


!> \brief Block kernel for DIVERGENCE_PART_2 — processes K-range [K1,K2].
!> Requires DIVERGENCE_PART_2_PREPROCESSING to have been called first.
!> Computes pressure zone DP contribution, solid cell zeroing, BC_LOOP,
!> DIV computation, and DDDT for the given K-range.
!> \param M Mesh data structure
!> \param DT Time step (s)
!> \param NM Mesh number
!> \param K1 K-range start (1-based inclusive)
!> \param K2 K-range end (1-based inclusive)

RECURSIVE SUBROUTINE DIVERGENCE_PART_2_BLOCK_KERNEL(M,DT,NM,K1,K2)

USE COMPLEX_GEOMETRY, ONLY : CC_CGSC, CC_UNKZ, CC_SOLID, CC_CUTCFE
USE CC_PRESSURE_KERNELS, ONLY : ADD_CUTCELL_D_PBAR_DT, &
   ADD_LINKEDCELL_D_PBAR_DT

TYPE(MESH_TYPE), INTENT(INOUT), TARGET :: M
INTEGER, INTENT(IN) :: NM,K1,K2
REAL(EB), INTENT(IN) :: DT
REAL(EB), POINTER, DIMENSION(:,:,:) :: DP,RTRM,DIV
REAL(EB) :: RDT,UN_P
REAL(EB), POINTER, DIMENSION(:) :: D_PBAR_DT_P
REAL(EB), POINTER, DIMENSION(:,:) :: PBAR_P
INTEGER :: IW,IC,I,J,K,IPZ,K_MIN
TYPE(WALL_TYPE), POINTER :: WC
TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1

IF (SOLID_PHASE_ONLY) RETURN
IF (PERIODIC_TEST==3) RETURN
IF (PERIODIC_TEST==4) RETURN

RDT = 1._EB/DT

SELECT CASE(PREDICTOR)
   CASE(.TRUE.)
      DP => M%DS
      PBAR_P => M%PBAR_S
   CASE(.FALSE.)
      DP => M%D
      PBAR_P => M%PBAR
END SELECT

RTRM => M%WORK1

! Add pressure derivative to divergence (K-restricted)

IF (N_ZONE>0) THEN

   IF (PREDICTOR) D_PBAR_DT_P => M%D_PBAR_DT_S
   IF (CORRECTOR) D_PBAR_DT_P => M%D_PBAR_DT

   DO K=K1,K2
      DO J=1,M%JBAR
         DO I=1,M%IBAR
            IPZ = M%PRESSURE_ZONE(I,J,K)
            IF (IPZ<1) CYCLE
            IF (M%CELL(M%CELL_INDEX(I,J,K))%SOLID) CYCLE
            DP(I,J,K) = DP(I,J,K) - (M%R_PBAR(K,IPZ)-RTRM(I,J,K))*D_PBAR_DT_P(IPZ)
         ENDDO
      ENDDO
   ENDDO

ENDIF

! Zero out divergence in solid cells (K-restricted)

DO K=K1,K2
   DO J=1,M%JBAR
      DO I=1,M%IBAR
         IC = M%CELL_INDEX(I,J,K)
         IF (M%CELL(IC)%SOLID) DP(I,J,K) = 0._EB
      ENDDO
   ENDDO
ENDDO

! Specify divergence in boundary cells to account for volume being generated at the walls (K-filtered)
! First block includes K=0 ghost cells; last block includes K=KBP1 ghost cells.

K_MIN = MERGE(0, K1, K1==1)

BC_LOOP: DO IW=1,M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS
   WC => M%WALL(IW)
   IF (WC%BOUNDARY_TYPE==NULL_BOUNDARY) CYCLE BC_LOOP
   BC=>M%BOUNDARY_COORD(WC%BC_INDEX)

   ! K-filter: skip wall cells outside this block's range
   IF (BC%KK < K_MIN .OR. BC%KK > K2) CYCLE BC_LOOP
   ! Also skip KBP1 ghost cells unless this is the last block
   IF (BC%KK > M%KBAR .AND. K2 < M%KBAR) CYCLE BC_LOOP

   SELECT CASE (WC%BOUNDARY_TYPE)
      CASE (SOLID_BOUNDARY)
         IF (.NOT.M%CELL(M%CELL_INDEX(BC%II,BC%JJ,BC%KK))%SOLID) CYCLE BC_LOOP
         B1 => M%BOUNDARY_PROP1(WC%BC_INDEX)
         IF (PREDICTOR) THEN
            UN_P = B1%U_NORMAL_S
         ELSE
            UN_P = B1%U_NORMAL
         ENDIF
         SELECT CASE(BC%IOR)
            CASE( 1)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDX(BC%II)*M%RRN(BC%II)*M%R(BC%II)
            CASE(-1)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDX(BC%II)*M%RRN(BC%II)*M%R(BC%II-1)
            CASE( 2)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDY(BC%JJ)
            CASE(-2)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDY(BC%JJ)
            CASE( 3)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDZ(BC%KK)
            CASE(-3)
               DP(BC%II,BC%JJ,BC%KK) = DP(BC%II,BC%JJ,BC%KK) - UN_P*M%RDZ(BC%KK)
         END SELECT
      CASE (OPEN_BOUNDARY,MIRROR_BOUNDARY,INTERPOLATED_BOUNDARY)
         DP(BC%II,BC%JJ,BC%KK) = DP(BC%IIG,BC%JJG,BC%KKG)
   END SELECT
ENDDO BC_LOOP

! Compute time derivative of the divergence, dD/dt (K-restricted)

DIV=>M%WORK1

IF (PREDICTOR) THEN
   DO K = K1,K2
      DO J = 1,M%JBAR
         DO I = 1,M%IBAR
            DIV(I,J,K) = (M%R(I)*M%U(I,J,K)-M%R(I-1)*M%U(I-1,J,K))*M%RDX(I)*M%RRN(I) + (M%V(I,J,K)-M%V(I,J-1,K))*M%RDY(J) + &
                         (M%W(I,J,K)-M%W(I,J,K-1))*M%RDZ(K)
         ENDDO
      ENDDO
   ENDDO
   DO K = K1,K2
      DO J = 1,M%JBAR
         DO I = 1,M%IBAR
            M%DDDT(I,J,K) = (DP(I,J,K)-DIV(I,J,K))*RDT
         ENDDO
      ENDDO
   ENDDO
ELSEIF (CORRECTOR) THEN
   DO K = K1,K2
      DO J = 1,M%JBAR
         DO I = 1,M%IBAR
            DIV(I,J,K) = (M%R(I)*M%U(I,J,K) -M%R(I-1)*M%U(I-1,J,K)) *M%RDX(I)*M%RRN(I) + (M%V(I,J,K)- M%V(I,J-1,K)) *M%RDY(J) + &
                         (M%W(I,J,K) -M%W(I,J,K-1)) *M%RDZ(K) &
                       + (M%R(I)*M%US(I,J,K)-M%R(I-1)*M%US(I-1,J,K))*M%RDX(I)*M%RRN(I) + (M%VS(I,J,K)-M%VS(I,J-1,K))*M%RDY(J) + &
                         (M%WS(I,J,K)-M%WS(I,J,K-1))*M%RDZ(K)
         ENDDO
      ENDDO
   ENDDO
   DO K = K1,K2
      DO J = 1,M%JBAR
         DO I = 1,M%IBAR
            M%DDDT(I,J,K) = (2._EB*DP(I,J,K)-DIV(I,J,K))*RDT
         ENDDO
      ENDDO
   ENDDO
ENDIF

END SUBROUTINE DIVERGENCE_PART_2_BLOCK_KERNEL



RECURSIVE SUBROUTINE CHECK_DIVERGENCE_KERNEL(M)

! Computes maximum velocity divergence

TYPE(MESH_TYPE), INTENT(INOUT), TARGET :: M
INTEGER  :: I,J,K
REAL(EB) :: DIV,RES
REAL(EB), POINTER, DIMENSION(:,:,:) :: UU,VV,WW,DP

IF (PREDICTOR) THEN
   UU=>M%US
   VV=>M%VS
   WW=>M%WS
   DP=>M%DS
ELSEIF (CORRECTOR) THEN
   UU=>M%U
   VV=>M%V
   WW=>M%W
   DP=>M%D
ENDIF

IF(STORE_CARTESIAN_DIVERGENCE) M%CARTVELDIV = DP

M%RESMAX = 0._EB
M%DIVMX  = -10000._EB
M%DIVMN  =  10000._EB
M%IMX    = 0
M%JMX    = 0
M%KMX    = 0

DO K=1,M%KBAR
   DO J=1,M%JBAR
      LOOP1: DO I=1,M%IBAR
         IF (M%CELL(M%CELL_INDEX(I,J,K))%SOLID) CYCLE LOOP1
         SELECT CASE(CYLINDRICAL)
            CASE(.FALSE.)
               DIV = (UU(I,J,K)-UU(I-1,J,K))*M%RDX(I) + &
                     (VV(I,J,K)-VV(I,J-1,K))*M%RDY(J) + &
                     (WW(I,J,K)-WW(I,J,K-1))*M%RDZ(K)
            CASE(.TRUE.)
               DIV = (M%R(I)*UU(I,J,K)-M%R(I-1)*UU(I-1,J,K))*M%RDX(I)*M%RRN(I) +  &
                     (WW(I,J,K)-WW(I,J,K-1))*M%RDZ(K)
         END SELECT
         IF(STORE_CARTESIAN_DIVERGENCE) M%CARTVELDIV(I,J,K) = DIV
         RES = ABS(DIV-DP(I,J,K))
         IF (ABS(RES)>=M%RESMAX) THEN
            M%RESMAX = ABS(RES)
            M%IRM=I
            M%JRM=J
            M%KRM=K
         ENDIF
         M%RESMAX = MAX(RES,M%RESMAX)
         IF (DIV>=M%DIVMX) THEN
            M%DIVMX = DIV
            M%IMX=I
            M%JMX=J
            M%KMX=K
         ENDIF
         IF (DIV<M%DIVMN) THEN
            M%DIVMN = DIV
            M%IMN=I
            M%JMN=J
            M%KMN=K
         ENDIF
      ENDDO LOOP1
   ENDDO
ENDDO

END SUBROUTINE CHECK_DIVERGENCE_KERNEL


