   RHO_Z_P(I,J,K) = RHOP(I,J,K)*ZZP(I,J,K,N)
         ENDDO
      ENDDO
   ENDDO

   ! Compute scalar face values

   FX_P(LBOUND(FX_ZZ,1):,LBOUND(FX_ZZ,2):,LBOUND(FX_ZZ,3):) => FX_ZZ(:,:,:,N)
   FY_P(LBOUND(FY_ZZ,1):,LBOUND(FY_ZZ,2):,LBOUND(FY_ZZ,3):) => FY_ZZ(:,:,:,N)
